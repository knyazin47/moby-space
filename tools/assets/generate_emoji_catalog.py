#!/usr/bin/env python3
"""Render the typed Dart emoji catalog from public JSON metadata; no APK input."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'frontend/lib/core/config/source_emoji_catalog.dart'


def format_emoji(row):
    values = row['code_points']
    if not values or any(type(value) is not int or not 0 <= value <= 0x10ffff for value in values):
        raise ValueError('Invalid Unicode code points')
    for name in ['sheet', 'row']:
        if type(row[name]) is not int or row[name] < 0:
            raise ValueError(f'Invalid emoji {name}')
    key = '_'.join(f'{value:x}' for value in values)
    expected_path = f'frontend/assets/emoji/emoji_{key}.png'
    if row['output_path'] != expected_path:
        raise ValueError('Emoji asset path does not match Unicode metadata')
    points = ', '.join(f'0x{value:x}' for value in values)
    children = ', '.join(format_emoji(child) for child in row.get('variants', []))
    return f"SourceEmoji(codePoints: [{points}], sheet: {row['sheet']}, row: {row['row']}, assetPath: 'assets/emoji/emoji_{key}.png', variants: [{children}])"


def render(manifest):
    lines = [
        '// Generated by tools/assets/generate_emoji_catalog.py from tools/assets/emoji.json.',
        '// Official image provenance: tools/assets/emoji-upstream.json; nested variants and category order retained.',
        '// dart format off',
        'class SourceEmoji {',
        '  const SourceEmoji({required this.codePoints, required this.sheet, required this.row, required this.assetPath, this.variants = const []});',
        '  final List<int> codePoints;',
        '  final int sheet;',
        '  final int row;',
        '  final String assetPath;',
        '  final List<SourceEmoji> variants;',
        '  String get text => String.fromCharCodes(codePoints);',
        '}',
        'class SourceEmojiCategory {',
        '  const SourceEmojiCategory({required this.id, required this.tabAssetPath, required this.emojis});',
        '  final String id;',
        '  final String tabAssetPath;',
        '  final List<SourceEmoji> emojis;',
        '}',
        'abstract final class SourceEmojiCatalog {',
        "  static const recentAssetPath = 'assets/emoji/tabs/emoji_recent.png';",
        "  static const backspaceAssetPath = 'assets/emoji/tabs/emoji_backspace.png';",
    ]
    categories = manifest['categories']
    identifiers = [category['id'] for category in categories]
    if len(set(identifiers)) != len(identifiers):
        raise ValueError('Duplicate emoji category')
    if any(row['category'] not in identifiers for row in manifest['emoji']):
        raise ValueError('Emoji belongs to an unknown category')
    for category in categories:
        identifier = category['id']
        if not re.fullmatch(r'[a-zA-Z][a-zA-Z0-9]*', identifier):
            raise ValueError('Invalid Dart emoji category identifier')
        rows = sorted((row for row in manifest['emoji'] if row['category'] == identifier), key=lambda row: row['category_index'])
        if len(rows) != category['imported_base_count'] or [row['category_index'] for row in rows] != list(range(len(rows))):
            raise ValueError('Emoji category count/order is incomplete')
        lines.append(f'  static const {identifier} = <SourceEmoji>[')
        lines.extend('    ' + format_emoji(row) + ',' for row in rows)
        lines.append('  ];')
    lines.append('  static const categories = <SourceEmojiCategory>[')
    for category in categories:
        path = category['tab_asset_path']
        if not re.fullmatch(r'assets/emoji/tabs/[a-zA-Z0-9_]+\.png', path):
            raise ValueError('Invalid emoji category tab path')
        lines.append(f"    SourceEmojiCategory(id: '{category['id']}', tabAssetPath: '{path}', emojis: {category['id']}),")
    lines.extend(['  ];', '}', ''])
    return '\n'.join(lines).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    payload = render(json.loads((ROOT / 'tools/assets/emoji.json').read_text()))
    if args.check:
        if OUTPUT.read_bytes() != payload:
            print('Emoji catalog drift: run python3 tools/assets/generate_emoji_catalog.py', file=sys.stderr)
            return 1
    else:
        OUTPUT.write_bytes(payload)
    print('Typed emoji catalog matches public JSON metadata')
    return 0


if __name__ == '__main__':
    sys.exit(main())
